-- T5.6: лише авторська загальна бібліотека, без персональних grants чи імпорту даних.
CREATE TABLE library_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type text NOT NULL CHECK (type IN ('article', 'video', 'playlist', 'instruction')),
    title text NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 255),
    summary text NULL CHECK (summary IS NULL OR length(summary) <= 2000),
    cover_image_url text NULL CHECK (cover_image_url IS NULL OR length(cover_image_url) <= 2048),
    content_markdown text NULL CHECK (content_markdown IS NULL OR length(content_markdown) <= 200000),
    external_url text NULL CHECK (external_url IS NULL OR (length(external_url) <= 2048 AND external_url ~ '^https://[^[:space:]]+$')),
    status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published')),
    published_at timestamptz NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT library_publication_time CHECK (
        (status='draft' AND published_at IS NULL) OR
        (status='published' AND published_at IS NOT NULL)
    ),
    CONSTRAINT library_published_source CHECK (
        status='draft' OR (
            (type IN ('video','playlist') AND external_url IS NOT NULL)
            OR
            (type IN ('article','instruction') AND
                ((content_markdown IS NOT NULL AND length(btrim(content_markdown)) > 0)
                  OR external_url IS NOT NULL))
        )
    )
);
CREATE INDEX library_published_order ON library_items (published_at DESC,id DESC) WHERE status='published';
